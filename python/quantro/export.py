"""
Quantro Code Export Engine
Utilities to export quantum circuits and simulation configurations to standalone
Python scripts, Qiskit executable programs, OpenQASM, and JSON data.
"""

from __future__ import annotations
import json
from typing import Any, Dict


def export_to_python(circuit) -> str:
    """Exports a circuit to a clean standalone Quantro Python script."""
    ops_lines = []
    for op in circuit.operations:
        g = op["gate"].lower()
        if g in ("h", "x", "y", "z", "s", "t"):
            ops_lines.append(f"qc.{g}({op['targets'][0]})")
        elif g in ("rx", "ry", "rz"):
            ops_lines.append(f"qc.{g}({op['targets'][0]}, theta={op['theta']:.6f})")
        elif g in ("cx", "cz"):
            ops_lines.append(f"qc.{g}({op['controls'][0]}, {op['targets'][0]})")
        elif g == "ccx":
            ops_lines.append(f"qc.toffoli({op['controls'][0]}, {op['controls'][1]}, {op['targets'][0]})")

    code = f'''#!/usr/bin/env python3
# Quantro Quantum Simulation Script
# Generated by Quantro Python SDK / Quantro Lab

import quantro as qtr

# Initialize {circuit.num_qubits}-qubit circuit
qc = qtr.QuantumCircuit({circuit.num_qubits})

# Applied Quantum Gates
''' + "\n".join(ops_lines) + '''

# Output State Probabilities
print("State Probabilities:")
for state, prob in qc.get_probabilities().items():
    print(f"|{state}> : {prob:.4f}")

# Measurement Sampling (1024 shots)
samples = qc.sample(shots=1024)
print("\\nMeasurement Counts (1024 shots):")
print(samples)
'''
    return code


def export_to_json(data: Any, indent: int = 2) -> str:
    """Serializes simulation data to JSON string."""
    def _default(obj):
        if isinstance(obj, complex):
            return {"real": obj.real, "imag": obj.imag}
        if hasattr(obj, "__dict__"):
            return obj.__dict__
        return str(obj)

    return json.dumps(data, default=_default, indent=indent)
